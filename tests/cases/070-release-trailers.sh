# The pull request check for release-note trailers, and the release-notes
# script that reads them back. Both use git's own trailer parser, so these
# need git; everything else here is plain shell.

if ! command -v git >/dev/null 2>&1; then
	printf '  skip release trailers (git not installed)\n'
else
	CHECK="$ROOT/.github/scripts/check-pr-trailers.sh"
	NOTES="$ROOT/.github/scripts/release-notes.sh"

	# check BODY: sets out and rc
	check() { out=$(printf '%b' "$1" | sh "$CHECK" 2>&1); rc=$?; }

	check 'Fix the thing.\n\nChangelog: Backups now run at 02:00.\n'
	assert_eq "$rc" 0 "a Changelog line passes"
	assert_contains "$out" "Changelog: Backups now run at 02:00." "the check prints what it found"

	check 'Tidy CI.\n\nchangelog: none\n'
	assert_eq "$rc" 0 "\"none\" passes, whatever its case"

	check 'Move to a data disk.\n\nChangelog: Data lives on its own disk.\nUpgrade-Action: Run utilities/migrate-to-data-disk.sh.\n'
	assert_eq "$rc" 0 "Changelog with Upgrade-Action passes"

	check 'Fix it.\r\n\r\nChangelog: Typed in the web editor.\r\n'
	assert_eq "$rc" 0 "CRLF line endings from the web editor pass"

	check 'Summary.\n\n---\n\nMore after a rule.\n\nChangelog: After a Markdown rule.\n'
	assert_eq "$rc" 0 "a --- rule earlier in the description is not a patch divider"

	check 'Fix.\n\nChangelog: Before a tool footer.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n'
	assert_eq "$rc" 0 "a closing footer after a --- line is set aside"

	check 'Fix.\n\n---\n\nChangelog: Below a final rule.\n'
	assert_eq "$rc" 0 "trailers below the last --- line still count"

	check 'Fix.\n\nChangelog: Before the footer.\n\n---\nSee also https://example.com\n\nThen more text.\n'
	assert_eq "$rc" 0 "the footer may run to several paragraphs"

	# GitHub wraps a description at 72 columns in the merge commit.
	check 'Fix.\n\nChangelog: A release note long enough that GitHub wraps it onto a\nsecond line in the merge commit.\nUpgrade-Action: Run the update script\nonce.\n'
	assert_eq "$rc" 0 "trailers wrapped onto a second line pass"
	assert_contains "$out" "Changelog: A release note long enough that GitHub wraps it onto a second line in the merge commit." "and are joined back into one line"
	assert_contains "$out" "Upgrade-Action: Run the update script once." "each of them"

	check 'No trailers at all.\n'
	assert_eq "$rc" 1 "a description without trailers fails"
	assert_contains "$out" "No Changelog trailer" "and says what is missing"

	check ''
	assert_eq "$rc" 1 "an empty description fails"

	check 'Changelog: Written at the top.\n\nThen more text after it.\n'
	assert_eq "$rc" 1 "a Changelog line that is not in the last paragraph fails"
	assert_contains "$out" "not in the last paragraph" "and says where it has to go"

	check 'Fix.\n\nChangelog:\n'
	assert_eq "$rc" 1 "an empty Changelog fails"

	check 'Fix.\n\nChangelog: none\nChangelog: Something real.\n'
	assert_eq "$rc" 1 "\"none\" next to a real line fails"

	check 'Fix.\n\nChangelog: none\nUpgrade-Action: Restart the stack.\n'
	assert_eq "$rc" 1 "\"none\" with an Upgrade-Action fails"
	assert_contains "$out" "belongs in the release notes" "and says why"

	check 'Fix.\n\nUpgrade-Action: Restart the stack.\n'
	assert_eq "$rc" 1 "an Upgrade-Action without a Changelog fails"

	out=$(sh "$CHECK" "$ROOT/.github/pull_request_template.md" 2>&1); rc=$?
	assert_eq "$rc" 1 "the pull request template, left as it is, fails"
	assert_contains "$out" "Changelog line is still the template's placeholder" "and names the Changelog placeholder"
	assert_contains "$out" "Upgrade-Action line is still the template's placeholder" "and the Upgrade-Action one"

	filled=$(sed -e 's/^Changelog: .*/Changelog: Something real./' -e '/^Upgrade-Action:/d' "$ROOT/.github/pull_request_template.md")
	check "$filled"
	assert_eq "$rc" 0 "the template passes once filled in, its comment and all"

	# release-notes.sh against a throwaway repository with two "merged pull
	# requests", one with no user-facing change, and a tag before them.
	repo="$WORK/release-notes"
	mkdir -p "$repo"
	(
		cd "$repo" || exit 1
		git init -q
		git config user.name test
		git config user.email test@example.com
		git commit -q --allow-empty -m "Start"
		git tag v1.0.0
		git commit -q --allow-empty -m "Merge pull request #7 from someone/branch

Move to a data disk

Changelog: Data lives on its own disk.
Upgrade-Action: Run utilities/migrate-to-data-disk.sh."
		git commit -q --allow-empty -m "Merge pull request #8 from someone/ci

Tidy CI

Changelog: none"
		git commit -q --allow-empty -m "Make backups survive a missing SMTP host (#9)

Changelog: Backups keep running without SMTP, even when the
notifications are on.

---
_Generated by a tool_"
	)
	notes=$(cd "$repo" && sh "$NOTES" 2>&1)
	assert_contains "$notes" "## Changes since v1.0.0" "release notes start from the latest tag"
	assert_contains "$notes" "- Data lives on its own disk. (#7)" "a Changelog line is listed with its pull request"
	assert_contains "$notes" "- Backups keep running without SMTP, even when the notifications are on. (#9)" "a title-and-description merge commit, wrapped, is listed with its pull request"
	assert_before "$notes" "(#7)" "(#9)" "in the order they were merged"
	assert_not_contains "$notes" "none" "\"Changelog: none\" is left out"
	assert_contains "$notes" "## Before you update an existing deployment" "upgrade actions get their own section"
	assert_contains "$notes" "- Run utilities/migrate-to-data-disk.sh. (#7)" "with the action and its pull request"
fi
